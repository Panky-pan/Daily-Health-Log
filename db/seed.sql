-- 【可重复执行】开头先清空两张表，再插入，跑多少遍结果完全一样
--   （TRUNCATE ... RESTART IDENTITY 会把 id 计数重置，所以重跑后每行 id 都相同）
--   若控制台报权限不足，把 TRUNCATE 那行换成：
--     DELETE FROM checkins;  DELETE FROM settings;
--   （代价：id 会接着上次继续涨，数据内容不受影响）
--
-- 【会丢数据】TRUNCATE 会清掉这两张表的全部现有内容。现在库里是空的，安全；
--   以后如果要保留真实数据，就别再跑这个文件。
--
-- 【数据设计思路】TECH_DESIGN 3.0 第 ② 步的要求：用"假日期 + 真实体重区间"，
--   而且要故意留断档，否则 streak / 坚持率的统计算法无从验证。
--   日期范围：2026-09-21 ~ 2026-10-01，共 11 天，其中 9-26、9-30 两天故意不打卡
--   → 实到 9 条记录，用它能算出：
--       当前 streak  = 1（10-01 当天有记录）
--       历史最长     = 5（09-21 ~ 09-25）
--       坚持率分母   = 09-21 至 09-30 共 10 天，打卡 8 天 → 80%
--   （分母算法见 PRD F3：start_date 起、算到"昨天"，不含当天）
--
--   ⚠ 这些天数的重复日期不能手改：改了就会和 start_date 的统计口径对不上。
-- ============================================================================


